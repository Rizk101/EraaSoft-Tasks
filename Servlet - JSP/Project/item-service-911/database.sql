CREATE TABLE ITEM (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    NAME VARCHAR2(255 CHAR) NOT NULL,
    PRICE NUMBER(12, 2) NOT NULL,
    TOTAL_NUMBER NUMBER(10, 0) NOT NULL,
    CONSTRAINT PK_ITEM PRIMARY KEY (ID),
    CONSTRAINT UK_ITEM_NAME UNIQUE (NAME),
    CONSTRAINT CHK_ITEM_NAME_LENGTH CHECK (LENGTH(TRIM(NAME)) BETWEEN 1 AND 255),
    CONSTRAINT CHK_ITEM_PRICE_POSITIVE CHECK (PRICE > 0),
    CONSTRAINT CHK_ITEM_TOTAL_NUMBER_NONNEGATIVE CHECK (TOTAL_NUMBER >= 0)
);

CREATE TABLE APP_USER (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    NAME VARCHAR2(100 CHAR) NOT NULL,
    EMAIL VARCHAR2(255 CHAR) NOT NULL,
    PASSWORD_HASH VARCHAR2(512 CHAR) NOT NULL,
    PASSWORD_SALT VARCHAR2(128 CHAR) NOT NULL,
    CONSTRAINT PK_APP_USER PRIMARY KEY (ID),
    CONSTRAINT UK_APP_USER_EMAIL UNIQUE (EMAIL)
);

CREATE TABLE ITEM_DETAILS (
    ITEM_ID NUMBER NOT NULL,
    DESCRIPTION VARCHAR2(1000 CHAR) NOT NULL,
    CATEGORY VARCHAR2(100 CHAR) NOT NULL,
    CONSTRAINT PK_ITEM_DETAILS PRIMARY KEY (ITEM_ID),
    CONSTRAINT FK_ITEM_DETAILS_ITEM FOREIGN KEY (ITEM_ID) REFERENCES ITEM (ID) ON DELETE CASCADE
);
