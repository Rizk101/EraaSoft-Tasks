-- 1. AVG Function
SELECT AVG(SALARY)
FROM HR.EMPLOYEES;

-- 2. COUNT Function
SELECT COUNT(*)
FROM HR.EMPLOYEES;

-- 3. MAX Function
SELECT MAX(SALARY)
FROM HR.EMPLOYEES;

-- 4. MIN Function
SELECT MIN(SALARY)
FROM HR.EMPLOYEES;

-- 5. SUM Function
SELECT SUM(SALARY)
FROM HR.EMPLOYEES;

-- 6. GROUP BY Department
SELECT DEPARTMENT_ID, AVG(SALARY)
FROM HR.EMPLOYEES
GROUP BY DEPARTMENT_ID;

-- 7. GROUP BY Job
SELECT JOB_ID, COUNT(*)
FROM HR.EMPLOYEES
GROUP BY JOB_ID;

-- 8. HAVING
SELECT DEPARTMENT_ID, SUM(SALARY)
FROM HR.EMPLOYEES
GROUP BY DEPARTMENT_ID
HAVING SUM(SALARY) > 50000;

-- 9. AVG Commission
SELECT AVG(COMMISSION_PCT)
FROM HR.EMPLOYEES
WHERE COMMISSION_PCT IS NOT NULL;

-- 10. COUNT Salary Greater Than 10000
SELECT COUNT(*)
FROM HR.EMPLOYEES
WHERE SALARY > 10000;

-- 11. MAX and MIN Together
SELECT JOB_ID, MAX(SALARY), MIN(SALARY)
FROM HR.EMPLOYEES
GROUP BY JOB_ID;

-- 12. SUM Salary by Manager
SELECT MANAGER_ID, SUM(SALARY)
FROM HR.EMPLOYEES
GROUP BY MANAGER_ID;

-- 13. GROUP BY Multiple Columns
SELECT DEPARTMENT_ID, JOB_ID, SUM(SALARY)
FROM HR.EMPLOYEES
GROUP BY DEPARTMENT_ID, JOB_ID;

-- 14. HAVING with COUNT
SELECT JOB_ID, COUNT(*)
FROM HR.EMPLOYEES
GROUP BY JOB_ID
HAVING COUNT(*) > 5;

-- 15. Aggregate Functions Together
SELECT DEPARTMENT_ID,
       COUNT(*) AS TOTAL_EMPLOYEES,
       AVG(SALARY) AS AVG_SALARY,
       MAX(SALARY) AS MAX_SALARY,
       MIN(SALARY) AS MIN_SALARY
FROM HR.EMPLOYEES
GROUP BY DEPARTMENT_ID;

-- 16. Complex HAVING
SELECT DEPARTMENT_ID
FROM HR.EMPLOYEES
GROUP BY DEPARTMENT_ID
HAVING AVG(SALARY) > 8000
AND COUNT(*) < 10;

-- 17. Department with Highest Total Salary
SELECT DEPARTMENT_ID, SUM(SALARY) AS TOTAL_SALARY
FROM HR.EMPLOYEES
GROUP BY DEPARTMENT_ID
ORDER BY TOTAL_SALARY DESC
FETCH FIRST 1 ROW ONLY;

-- 18. Using Aliases
SELECT DEPARTMENT_ID,
       SUM(SALARY) AS TOTAL_SALARY,
       AVG(SALARY) AS AVERAGE_SALARY
FROM HR.EMPLOYEES
GROUP BY DEPARTMENT_ID;